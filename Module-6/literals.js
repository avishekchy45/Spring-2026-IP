// Template literals in JavaScript
// `(backticks) are used to create template literals, which allow for string interpolation and multi-line strings.

const name = "Bill Gates";
const age = 26;

const message = `My name is ${name} and I am ${age} years old.`;

console.log(message);

// Expression inside template literal

const a = 10;
const b = 20;

console.log(`The sum is ${a + b}`);

// Multi-line string

const message2 = `
Name: Bill Gates
Age: 26
Department: CSE
`;

console.log(message2);
